#!/usr/bin/env node
/**
 * Builds the Postman collection from the OpenAPI document.
 *
 * The endpoints are generated, so they cannot go stale: change a Laravel route
 * or a form request, run `make api-docs`, and the collection follows. What is
 * hand-written here is the part a generator cannot know - how to authenticate -
 * and that does not change when endpoints do.
 *
 * Edit this file, never docs/postman/collection.json. The JSON is output.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { convert } = require("openapi-to-postmanv2");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = join(root, "apps/api/openapi.json");
const OUT_DIR = join(root, "docs/postman");

/**
 * Runs before every request in the collection.
 *
 * Two jobs, and the first is the one people lose an afternoon to.
 *
 * Sanctum decides whether a request may be authenticated by a session cookie
 * by matching Origin or Referer against SANCTUM_STATEFUL_DOMAINS (ADR 0002).
 * A browser sends those headers on its own; Postman does not. Without them
 * every request arrives anonymous while carrying a perfectly valid session
 * cookie, which looks exactly like the session having broken.
 *
 * The second is CSRF: read the XSRF-TOKEN cookie per unsafe request, fetching
 * one first if there is none. Never cached, because Laravel rotates the token
 * when the session regenerates on sign-in.
 *
 * The session itself needs no handling at all - Postman's cookie jar carries
 * it, so `auth.login` once and every later request is authenticated.
 */
const PRE_REQUEST_SCRIPT = `
// Generated by scripts/build-postman-collection.mjs. Do not edit here.

var origin = (pm.environment.get("origin") || pm.collectionVariables.get("origin") || "").replace(/\\/+$/, "");

if (!origin) {
    throw new Error("Set the 'origin' variable to the web application's URL, for example http://localhost:3000");
}

// Sanctum matches Origin or Referer against SANCTUM_STATEFUL_DOMAINS to decide
// whether a request may hold a session. A browser sends these; Postman does
// not. Without them every request is anonymous, with a valid session cookie
// attached - which reads as the session being broken rather than as a missing
// header.
pm.request.headers.upsert({ key: "Origin", value: origin });
pm.request.headers.upsert({ key: "Referer", value: origin + "/" });
pm.request.headers.upsert({ key: "Accept", value: "application/json" });

var method = (pm.request.method || "GET").toUpperCase();
var isUnsafe = ["POST", "PUT", "PATCH", "DELETE"].indexOf(method) !== -1;

if (isUnsafe) {
    var jar = pm.cookies.jar();

    var applyToken = function (token) {
        if (!token) {
            return;
        }
        // Laravel percent-encodes the cookie and decodes it again before
        // comparing, so it has to be sent decoded.
        pm.request.headers.upsert({ key: "X-XSRF-TOKEN", value: decodeURIComponent(token) });
    };

    // Read per request, never cached: Laravel rotates the token when the
    // session regenerates on sign-in, and a stale one is a 419 on the first
    // write afterwards.
    jar.get(origin, "XSRF-TOKEN", function (err, token) {
        if (!err && token) {
            applyToken(token);
            return;
        }

        pm.sendRequest({
            url: origin + "/api/v1/auth/csrf-cookie",
            method: "GET",
            header: {
                Origin: origin,
                Referer: origin + "/",
                Accept: "application/json"
            }
        }, function () {
            jar.get(origin, "XSRF-TOKEN", function (error, fresh) {
                applyToken(fresh);
            });
        });
    });
}
`.trim();

const DESCRIPTION = [
  "Generated from apps/api/openapi.json. Do not edit by hand - run `make api-docs`.",
  "",
  "## Before you start",
  "",
  "Set `origin` to the web application's URL, not the API's. The API is not",
  "published: it is reached at /api/v1 on the web origin, which proxies to it.",
  "In development that is http://localhost:3000 unless WEB_PORT was changed.",
  "",
  "Postman needs permission to read cookies programmatically. If requests come",
  "back 419, allow the origin under Cookies -> Domains allowlist.",
  "",
  "## Authentication",
  "",
  "Handled by the collection's pre-request script. Send `auth.register` or",
  "`auth.login` once and every later request is authenticated - the session",
  "cookie lives in Postman's cookie jar, and CSRF is fetched and attached",
  "automatically. There is nothing to copy between requests.",
].join("\n");

/** Requests whose example body should use collection variables instead of placeholders. */
const CREDENTIAL_FIELDS = {
  // `remember` is set because the converter emits the literal string
  // "<boolean>" for an optional field, which fails validation as a boolean.
  "auth.login": { email: "{{email}}", password: "{{password}}", remember: false },
  "auth.register": {
    email: "{{email}}",
    password: "{{password}}",
    password_confirmation: "{{password}}",
  },
  "auth.password.forgot": { email: "{{email}}" },
};

/**
 * The order somebody actually works in, rather than the order the generator
 * happened to emit. Anything not listed keeps its position, after these.
 */
const ORDER = [
  "auth.csrf-cookie",
  "auth.register",
  "auth.login",
  "auth.me",
  "auth.logout",
  "email",
  "password",
];

/**
 * The converter names a request after its summary, which for the CSRF route is
 * a whole sentence. Renamed by path rather than by matching that sentence, so
 * an edit to the controller's docblock does not silently stop renaming it.
 */
function renameByPath(item) {
  const path = item.request?.url?.path;

  if (Array.isArray(path) && path[path.length - 1] === "csrf-cookie") {
    item.name = "auth.csrf-cookie";
  }
}

function sortTree(items) {
  for (const item of items) {
    if (Array.isArray(item.item)) {
      sortTree(item.item);
    }
  }

  items.sort((a, b) => {
    const left = ORDER.indexOf(a.name);
    const right = ORDER.indexOf(b.name);

    return (left === -1 ? ORDER.length : left) - (right === -1 ? ORDER.length : right);
  });
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Removes the random identifiers the converter mints on every run.
 *
 * Without this the output is different each time it is generated - 72 lines of
 * fresh UUIDs - so `make api-check` could never be green and the drift check
 * would be worthless. Postman assigns its own identifiers on import, so
 * nothing needs these.
 *
 * A generated artifact that is committed has to be deterministic, or it is not
 * really a check.
 */
function stripGeneratedIds(node) {
  if (Array.isArray(node)) {
    node.forEach(stripGeneratedIds);

    return;
  }

  if (node === null || typeof node !== "object") {
    return;
  }

  if (typeof node.id === "string" && UUID.test(node.id)) {
    delete node.id;
  }

  delete node._postman_id;

  // Saved example responses, which the converter fills with fresh random
  // values every run - a random integer for each `id`, and a random number of
  // entries for a map like Laravel's validation `errors`. They are
  // illustrative only, and apps/api/openapi.json documents every response
  // properly, so dropping them costs nothing and buys a check that can pass.
  if (Array.isArray(node.response)) {
    delete node.response;
  }

  Object.values(node).forEach(stripGeneratedIds);
}

function eachRequest(items, visit) {
  for (const item of items) {
    if (Array.isArray(item.item)) {
      eachRequest(item.item, visit);
    } else if (item.request) {
      visit(item);
    }
  }
}

function applyCredentialVariables(item) {
  const fields = CREDENTIAL_FIELDS[item.name];

  if (!fields || !item.request.body?.raw) {
    return;
  }

  let body;
  try {
    body = JSON.parse(item.request.body.raw);
  } catch {
    // The converter emits an example that is not valid JSON. Leave it alone
    // rather than guessing at it.
    return;
  }

  item.request.body.raw = JSON.stringify({ ...body, ...fields }, null, 2);
}

const spec = readFileSync(SPEC, "utf8");

convert({ type: "string", data: spec }, { folderStrategy: "Paths" }, (error, result) => {
  if (error || !result?.result) {
    console.error("Could not convert the OpenAPI document:", error ?? result?.reason);
    process.exit(1);
  }

  const collection = result.output[0].data;

  collection.info.name = "Laravel Commerce API";
  collection.info.description = DESCRIPTION;

  // `baseUrl` arrives as the spec's relative server, "/api/v1". Redefining it
  // in terms of `origin` is what lets one variable move the whole collection
  // between local, staging and a colleague's port.
  collection.variable = [
    {
      key: "origin",
      value: "http://localhost:3000",
      type: "string",
    },
    { key: "baseUrl", value: "{{origin}}/api/v1", type: "string" },
    { key: "email", value: "aino@example.com", type: "string" },
    { key: "password", value: "correct-horse-battery", type: "string" },
  ];

  collection.event = [
    {
      listen: "prerequest",
      script: { type: "text/javascript", exec: PRE_REQUEST_SCRIPT.split("\n") },
    },
  ];

  eachRequest(collection.item, renameByPath);
  eachRequest(collection.item, applyCredentialVariables);
  sortTree(collection.item);
  stripGeneratedIds(collection);

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, "collection.json"), `${JSON.stringify(collection, null, 2)}\n`);

  const environment = {
    name: "Laravel Commerce - local",
    values: [
      { key: "origin", value: "http://localhost:3000", type: "default", enabled: true },
      { key: "email", value: "aino@example.com", type: "default", enabled: true },
      { key: "password", value: "correct-horse-battery", type: "secret", enabled: true },
    ],
    _postman_variable_scope: "environment",
  };

  writeFileSync(join(OUT_DIR, "environment.json"), `${JSON.stringify(environment, null, 2)}\n`);

  let count = 0;
  eachRequest(collection.item, () => count++);
  console.log(`Postman collection built: ${count} requests.`);
});
